"""Vectorised prediction update for layers of regular continuous nodes."""

import dataclasses
from typing import Callable, Optional

import jax.numpy as jnp

from pyhgf.coupling import Coupling
from pyhgf.typing.vectorised import LayerParams, LayerState
from pyhgf.updates.prediction.continuous import MIN_PREDICTED_VARIANCE


def vectorised_continuous_prediction(
    child_state: LayerState,
    params: LayerParams,
    time_step: float,
    value_parent_state: Optional[LayerState] = None,
    weights: Optional[jnp.ndarray] = None,
    coupling_fn: Optional[Callable] = None,
    volatility_parent_state: Optional[LayerState] = None,
    volatility_weights: Optional[jnp.ndarray] = None,
    is_input_layer: bool = False,
    mean_field_updates: bool = False,
    coupling_moments: str = "taylor",
) -> LayerState:
    r"""Predict expected mean and precisions for a layer of continuous nodes.

    This is the vectorised equivalent of
    :func:`pyhgf.updates.prediction.continuous.continuous_node_prediction`, applied
    to a whole layer at once with the value and volatility parents generalised to
    *layers* connected by matrices.

    The expected mean follows the standard HGF drift semantics,

    .. math::

        \hat{\mu}_a^{(k)} = \lambda_a \mu_a^{(k-1)}
            + t^{(k)} \left( \rho_a + \sum_b W_{a,b} \, g(\hat{\mu}_b) \right),

    so the value parent nudges the child's own autoregressive state rather than
    replacing it (contrast with
    :func:`pyhgf.updates.vectorised.volatile.prediction.vectorised_layer_prediction`,
    where the parent's prediction fully determines the child's expected mean).

    The two predicted precisions follow the relaxed HGF (rHGF) scheme of the
    nodalised backend, with the value parent's first-order Taylor term; the
    volatility parents enter at their predicted means:

    .. math::

        \Omega_a^{(k)} = t^{(k)} \exp\!\left( \omega_a
            + \sum_j \kappa_{a,j} \hat{\mu}_j \right), \qquad
        \bar{\pi}_a^{(k)} = \left( \frac{\lambda_a^2}{\pi_a^{(k-1)}} + \Omega_a^{(k)}
            \right)^{-1},

    .. math::

        \frac{1}{\hat{\pi}_a^{(k)}} = \frac{1}{\bar{\pi}_a^{(k)}}
            + \sum_b \frac{(t^{(k)} W_{a,b} \, g'(\hat{\mu}_b))^2}{\hat{\pi}_b},
        \qquad
        \gamma_a^{(k)} = \Omega_a^{(k)} \, \hat{\pi}_a^{(k)}.

    Unlike the volatile-layer kernel, the Taylor value-coupling term carries the
    time step (the drift contribution to the mean is scaled by :math:`t^{(k)}`),
    matching the nodalised backend exactly. The observation layer is generated by its
    value parent rather than drifted by it (Eq. 64 of [1]_): its drift does not take
    the time step, as in
    :func:`pyhgf.updates.prediction.continuous.predict_mean`.

    The carried variance takes :math:`\lambda_a^2` (scaling the belief by
    :math:`\lambda_a` scales its variance by :math:`\lambda_a^2`):
    shrinking the mean by :math:`\lambda_a` shrinks the variance by
    :math:`\lambda_a^2`.

    The clamped observation layer :math:`u` is observed exactly. Both of its predicted
    precisions are the precision of its observation noise: its prior :math:`\pi_u`
    without volatility parent; with one, the volatility parent :math:`q` is a noise
    parent (Eq. 66 of [1]_), :math:`\hat{\pi}_u^{(k)} = \exp(-\omega_u
    - \sum_j \kappa_{u,j} \hat{\mu}_{q,j})`, and :math:`\gamma_u = 1`, as in
    :func:`pyhgf.updates.prediction.continuous.predict_noise_precision`.

    With ``coupling_moments="exact"``, the coupling function is replaced by its
    statistical linearisation under the predicted belief
    :math:`x_b \sim \mathcal{N}(\hat{\mu}_b, 1/\hat{\pi}_b)` of the value parent, as
    in :func:`pyhgf.updates.prediction.continuous.predict_value_coupling_variance`:
    the drift takes :math:`\mathbb{E}[g(x_b)]`, the slope :math:`g'(\hat{\mu}_b)`
    becomes the mean slope :math:`A_b = \mathbb{E}[g'(x_b)]`, and the variance
    :math:`R_b = \mathrm{Var}[g(x_b)] - A_b^2 / \hat{\pi}_b` of the residual of the
    linear function adds :math:`\sum_b (t^{(k)} W_{a,b})^2 R_b` to the conditional
    predicted variance :math:`1/\bar{\pi}_a^{(k)}`, and to the variance of the
    observation noise of the observation layer (without the time step).

    Parameters
    ----------
    child_state :
        Current state of the layer being predicted.
    params :
        The layer's parameters; ``tonic_volatility``, ``tonic_drift`` and
        ``autoconnection_strength`` must be set (see
        :meth:`pyhgf.typing.vectorised.LayerParams.create_continuous`).
    time_step :
        Time step :math:`t^{(k)}` for the prediction.
    value_parent_state :
        State of the value-parent layer, or ``None`` when the layer has no value
        parent (the drift is then :math:`\rho` alone).
    weights :
        Value-coupling matrix connecting this layer to its value parent, shape
        ``(n_self, n_parent)``. Required with *value_parent_state*.
    coupling_fn :
        Coupling function applied elementwise to the value parent's expected
        means. Required with *value_parent_state*.
    volatility_parent_state :
        State of the volatility-parent layer, or ``None`` when the layer's
        volatility is tonic only.
    volatility_weights :
        Volatility-coupling matrix :math:`\kappa`, shape ``(n_self, n_parent)``.
        Required with *volatility_parent_state*.
    is_input_layer :
        If True, the layer is the clamped observation leaf, whose predicted
        precisions are the precision of its observation noise (see above).
    mean_field_updates :
        If ``True``, use the mean-field prediction: the value parent's Taylor
        variance term is dropped, so the conditional and the marginal predicted
        precision coincide, as in
        :func:`pyhgf.updates.prediction.continuous.predict_precision_mean_field`.
    coupling_moments :
        ``"taylor"`` (default) linearises the coupling function at the expected means
        of the value parent. ``"exact"`` uses its moments under the predicted belief
        of the value parent. Not read with ``mean_field_updates``.

    Returns
    -------
    LayerState
        Updated layer state with ``expected_mean``, ``expected_precision``,
        ``conditional_expected_precision``, ``effective_precision`` and
        ``residual_variance`` populated.

    References
    ----------
    .. [1] Weber, L. A., Waade, P. T., Legrand, N., Møller, A. H., Stephan, K. E., &
       Mathys, C. (2026). The generalized hierarchical Gaussian filter.
       doi:10.7554/elife.110174.1
    """
    assert params.tonic_drift is not None
    assert params.tonic_volatility is not None
    assert params.autoconnection_strength is not None

    # 1. Expected mean: autoregression plus time-scaled drift. The observation layer
    # is generated by its value parent rather than drifted by it (Eq. 64 of Weber et
    # al., 2026), so its drift does not take the time step.
    drift_scale = 1.0 if is_input_layer else time_step
    driftrate = params.tonic_drift
    exact_moments = (
        coupling_moments == "exact"
        and value_parent_state is not None
        and not mean_field_updates
    )
    if value_parent_state is not None:
        assert weights is not None and coupling_fn is not None
        # Linear stand-in of g around the parent's expected mean: its value, its
        # slope A_b and the variance of its residual. The first-order Taylor expansion
        # gives g(μ̂_b), g'(μ̂_b) and no residual; the exact moments give E[g], E[g']
        # and the residual variance under the predicted belief N(μ̂_b, 1/π̂_b).
        coupled_parents, g_prime, residual = Coupling.from_callable(
            coupling_fn
        ).linearise(
            value_parent_state.expected_mean,
            1.0 / value_parent_state.expected_precision,
            "exact" if exact_moments else "taylor",
        )
        driftrate = driftrate + jnp.matmul(weights, coupled_parents)
    expected_mean = (
        params.autoconnection_strength * child_state.mean + drift_scale * driftrate
    )

    # 2. Total volatility: the volatility parents enter at their predicted means.
    total_volatility = params.tonic_volatility
    if volatility_parent_state is not None:
        assert volatility_weights is not None
        total_volatility = total_volatility + jnp.matmul(
            volatility_weights, volatility_parent_state.expected_mean
        )
    predicted_volatility = time_step * jnp.exp(total_volatility)
    predicted_volatility = jnp.where(
        predicted_volatility > 1e-128, predicted_volatility, jnp.nan
    )

    # 3. Value-coupling variance: Σ_b (t · W_ab · A_b)² / π̂_b, and with the exact
    # moments the residual variance Σ_b (t · W_ab)² · R_b. Absent under mean-field,
    # where value parents enter at their means alone.
    value_coupling_variance = jnp.zeros_like(child_state.precision)
    residual_variance = jnp.zeros_like(child_state.precision)
    if value_parent_state is not None and not mean_field_updates:
        assert weights is not None
        if exact_moments:
            residual_variance = (drift_scale**2) * jnp.matmul(weights**2, residual)
        value_coupling_variance = (drift_scale**2) * jnp.matmul(
            weights**2, g_prime**2 / value_parent_state.expected_precision
        )

    # 4. Conditional (π̄) and marginal (π̂) predicted precisions, effective γ.
    # Scaling the belief by λ scales its variance by λ². The drift is added after
    # the autoregression, so the value-coupling term is unscaled. With the exact
    # moments, the residual of the linearised coupling function does not depend on
    # the parent's value and adds to the conditional variance.
    carried_variance = (params.autoconnection_strength**2) / child_state.precision
    conditional_variance = carried_variance + predicted_volatility
    if exact_moments:
        conditional_variance = conditional_variance + residual_variance
    conditional_expected_precision = 1.0 / jnp.maximum(
        conditional_variance, MIN_PREDICTED_VARIANCE
    )
    expected_precision = 1.0 / jnp.maximum(
        conditional_variance + value_coupling_variance,
        MIN_PREDICTED_VARIANCE,
    )
    effective_precision = predicted_volatility * expected_precision

    # 5. Input layer: observed exactly, without random walk between observations.
    # Both predicted precisions are the precision of the observation noise: the
    # prior π without volatility parent; with one, the noise parent sets it as in
    # Eq. 66 of Weber et al. (2026), π̂ = exp(-(ω + κ μ̂)), and γ = 1 (Eq. 73).
    if is_input_layer:
        if volatility_parent_state is None:
            expected_precision = child_state.precision
            effective_precision = jnp.zeros_like(expected_precision)
        else:
            assert volatility_weights is not None
            expected_precision = jnp.exp(
                -params.tonic_volatility
                - jnp.matmul(volatility_weights, volatility_parent_state.expected_mean)
            )
            effective_precision = jnp.ones_like(expected_precision)
        if exact_moments:
            # The residual of the linearised coupling function adds to the variance
            # of the observation noise.
            expected_precision = 1.0 / (1.0 / expected_precision + residual_variance)
        conditional_expected_precision = expected_precision

    return dataclasses.replace(
        child_state,
        expected_mean=expected_mean,
        expected_precision=expected_precision,
        conditional_expected_precision=conditional_expected_precision,
        effective_precision=effective_precision,
        residual_variance=residual_variance,
    )
