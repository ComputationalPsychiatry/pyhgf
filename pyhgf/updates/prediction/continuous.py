from functools import partial
from typing import Callable

import jax.numpy as jnp
from jax import Array, jit

from pyhgf.coupling import resolve_coupling_fn
from pyhgf.typing import Edges

#: Floor on the total predicted variance (carried + volatility + value-coupling).
#: At λ = 0 the carried term vanishes, so without it the precision can diverge as
#: Ω → 0; at the default λ = 1 the sum already exceeds it, so it never binds.
MIN_PREDICTED_VARIANCE = 1e-128


@partial(jit, static_argnames=("edges", "node_idx", "coupling_moments"))
def predict_mean(
    attributes: dict,
    edges: Edges,
    node_idx: int,
    coupling_moments: str = "taylor",
) -> Array:
    r"""Compute the expected mean of a continuous state node.

    The expected mean at time :math:`k` for a state node :math:`a` with optional value
    parent(s) :math:`b` is in [1]_ given by:

    .. math::

        \hat{\mu}_a^{(k)} = \lambda_a \mu_a^{(k-1)} + P_a^{(k)}

    where :math:`P_a^{(k)}` is the drift rate (the total predicted drift of the expected
    mean, which sums the tonic and - optionally - phasic drifts). The variable
    :math:`lambda_a` represents the state's autoconnection strength, with
    :math:`\lambda_a \in [0, 1]`. When :math:`\lambda_a = 1`, the node is performing a
    Gaussian Random Walk using the value :math:`P_a^{(k)}` as total drift rate. When
    :math:`\lambda_a < 1`, the state will revert back to the total mean :math:`M_a`,
    which is given by:

    .. math::
            M_a = \frac{\rho_a + f\left(\hat{\mu}_b^{(k)}\right)} {1-\lambda_a},

    If :math:`\lambda_a = 0`, the node is not influenced by its own mean anymore, but
    by the value received by the value parent.

    The drift is a rate, :math:`P_a^{(k)} = t^{(k)} (\rho_a + \sum_b \alpha_{b,a}
    g_{b,a}(\hat{\mu}_b^{(k)}))` (Eq. 36 of [1]_). An input node (a continuous leaf)
    is generated by its value parents rather than drifted by them (Eq. 64 of [1]_), so
    its drift does not take the time step.

    With ``coupling_moments="exact"``, each value parent enters the drift through
    the mean of its coupling function under its predicted belief,
    :math:`\mathbb{E}[g_{b,a}(x_b)]` with
    :math:`x_b \sim \mathcal{N}(\hat{\mu}_b^{(k)}, 1/\hat{\pi}_b^{(k)})`, in place of
    :math:`g_{b,a}(\hat{\mu}_b^{(k)})` (see :meth:`pyhgf.coupling.Coupling.moments`).

    .. hint::

        By combining one parameter :math:`\lambda_a \in [0, 1]` and the influence of
        value parents, it is possible to implement both Gaussian Random Walks and
        Autoregressive Processes, without requiring specific coupling types.

    Parameters
    ----------
    attributes :
        The attributes of the probabilistic network that contains the continuous state
        node.
    edges :
        The edges of the probabilistic network as a tuple of
        :py:class:`pyhgf.typing.Indexes`. The tuple has the same length as the number of
        nodes. For each node, the index list value/volatility - parents/children.
    node_idx :
        Index of the node that should be updated.
    coupling_moments :
        ``"taylor"`` (default) evaluates the coupling functions at the expected means
        of the value parents. ``"exact"`` takes their means under the predicted
        beliefs of the value parents.

    Returns
    -------
    expected_mean :
        The new expected mean of the state node.

    References
    ----------
    .. [1] Weber, L. A., Waade, P. T., Legrand, N., Møller, A. H., Stephan, K. E., &
       Mathys, C. (2026). The generalized hierarchical Gaussian filter.
       doi:10.7554/elife.110174.1

    """
    # The time step scales the drift of a state node, but not that of an input node,
    # which its value parents generate rather than drift.
    is_input_node = (
        edges[node_idx].value_children is None
        and edges[node_idx].volatility_children is None
    )
    time_scale = 1.0 if is_input_node else attributes[-1]["time_step"]

    # List the node's value parents
    value_parents_idxs = edges[node_idx].value_parents

    # Get the drift rate from the node
    driftrate = attributes[node_idx]["tonic_drift"]

    # Look at the (optional) value parents for this node
    # and update the drift rate accordingly
    if value_parents_idxs is not None:
        for value_parent_idx, alpha in zip(
            value_parents_idxs,
            attributes[node_idx]["value_coupling_parents"],
        ):
            # look at each value parent
            # and get the coupling function to compute the drift
            child_position = edges[value_parent_idx].value_children.index(node_idx)
            coupling = resolve_coupling_fn(
                edges[value_parent_idx].coupling_fn[child_position]
            )
            if coupling is None:
                parent_value = attributes[value_parent_idx]["expected_mean"]
            else:
                parent_value, _, _ = coupling.linearise(
                    attributes[value_parent_idx]["expected_mean"],
                    1.0 / attributes[value_parent_idx]["expected_precision"],
                    coupling_moments,
                )

            driftrate += alpha * parent_value

    # The new expected mean from the previous value
    expected_mean = (
        attributes[node_idx]["autoconnection_strength"] * attributes[node_idx]["mean"]
    ) + (time_scale * driftrate)

    return expected_mean


@partial(jit, static_argnames=("edges", "node_idx", "coupling_moments"))
def predict_value_coupling_variance(
    attributes: dict, edges: Edges, node_idx: int, coupling_moments: str = "taylor"
) -> tuple[Array, Array]:
    r"""Compute the variance that the value parents add to the prediction of a node.

    Each value parent :math:`b` of the node :math:`a` enters through a linear function
    of its value around its expected mean, with a slope :math:`A_b` and a residual of
    variance :math:`R_b` (:meth:`pyhgf.coupling.Coupling.linearise`): the first-order
    Taylor expansion of its coupling function with ``coupling_moments="taylor"``
    (:math:`A_b = g'(\hat{\mu}_b)`, :math:`R_b = 0`), or its statistical linearisation
    under the predicted belief of the parent with ``coupling_moments="exact"``
    (section II-A of [1]_; :math:`A_b = \mathbb{E}[g'(x_b)]`,
    :math:`R_b = \mathrm{Var}[g(x_b)] - A_b^2 / \hat{\pi}_b`). The belief
    :math:`x_b \sim \mathcal{N}(\hat{\mu}_b, 1/\hat{\pi}_b)` of the parent adds the two
    variances

    .. math::

        V^{\mathrm{slope}}_a = \sum_b \frac{(t_a \alpha_{b,a} A_b)^2}{\hat{\pi}_b},
        \qquad
        V^{\mathrm{res}}_a = \sum_b (t_a \alpha_{b,a})^2 R_b,

    to the prediction of the node, with :math:`t_a` the time step for a state node,
    whose drift the time step scales, and 1 for an input node. With ``"exact"``, they
    sum to :math:`\sum_b (t_a \alpha_{b,a})^2 \mathrm{Var}[g(x_b)]`, the variance of
    the drift under the beliefs of the parents. A linear coupling has
    :math:`A_b = 1` and :math:`R_b = 0` in both cases.

    Parameters
    ----------
    attributes :
        The attributes of the probabilistic network.
    edges :
        The edges of the probabilistic network as a tuple of
        :py:class:`pyhgf.typing.AdjacencyLists`.
    node_idx :
        Index of the node that is predicted.
    coupling_moments :
        ``"taylor"`` (default) or ``"exact"``, see above.

    Returns
    -------
    slope_variance :
        The variance :math:`V^{\mathrm{slope}}_a` that the parents add through the
        slopes of the linear functions.
    residual_variance :
        The variance :math:`V^{\mathrm{res}}_a` of the residuals of the linear
        functions, which is 0 with ``coupling_moments="taylor"``.

    References
    ----------
    .. [1] García-Fernández, Á. F., Svensson, L., Morelande, M. R., & Särkkä, S.
       (2015). Posterior linearization filter: principles and implementation using
       sigma points. IEEE Transactions on Signal Processing, 63(20), 5561 to 5573.
       doi:10.1109/TSP.2015.2454485
    """
    # The time step scales the drift of a state node, but not that of an input node,
    # which its value parents generate rather than drift (see :func:`predict_mean`).
    is_input_node = (
        edges[node_idx].value_children is None
        and edges[node_idx].volatility_children is None
    )
    time_scale = 1.0 if is_input_node else attributes[-1]["time_step"]

    slope_variance = jnp.zeros_like(attributes[node_idx]["expected_precision"])
    residual_variance = jnp.zeros_like(attributes[node_idx]["expected_precision"])
    value_parents_idxs = edges[node_idx].value_parents
    if value_parents_idxs is not None:
        for value_parent_idx, alpha in zip(
            value_parents_idxs,
            attributes[node_idx]["value_coupling_parents"],
        ):
            child_position = edges[value_parent_idx].value_children.index(node_idx)
            coupling = resolve_coupling_fn(
                edges[value_parent_idx].coupling_fn[child_position]
            )
            mu_b = attributes[value_parent_idx]["expected_mean"]
            pi_b = attributes[value_parent_idx]["expected_precision"]
            if coupling is None:
                slope = jnp.ones_like(mu_b)
            else:
                _, slope, residual = coupling.linearise(
                    mu_b, 1.0 / pi_b, coupling_moments
                )
                residual_variance += (time_scale * alpha) ** 2 * residual

            slope_variance += (time_scale * alpha * slope) ** 2 / pi_b

    return slope_variance, residual_variance


@partial(jit, static_argnames=("edges", "node_idx", "coupling_moments"))
def predict_precision(
    attributes: dict, edges: Edges, node_idx: int, coupling_moments: str = "taylor"
) -> tuple[Array, Array, Array]:
    r"""Compute the predicted precisions of a continuous state node (no mean-field).

    This is the prediction step of the relaxed HGF (rHGF), which marginalises over the
    value parents' variational Gaussians rather than collapsing them to point
    estimates. One variance term appears relative to the canonical (g)HGF formulation
    [1]_: a **first-order Taylor** value-coupling term arising from the linearisation
    of the coupling function around the parent's predicted mean. The term vanishes in
    the limit of perfectly known value parents, recovering the canonical formula
    exactly. Volatility parents enter at their predicted means, as in [1]_.

    Two predicted precisions are computed and stored on the node (see
    :class:`pyhgf.typing.LayerState` for the notation table):

    .. math::

        \frac{1}{\bar{\pi}_a^{(k)}} = \frac{\lambda_a^2}{\pi_a^{(k-1)}}
            + \Omega_a^{(k)},

    .. math::

        \frac{1}{\hat{\pi}_a^{(k)}}
            \;=\; \frac{1}{\bar{\pi}_a^{(k)}}
              + \sum_{b} \frac{ (t^{(k)} \alpha_{b,a} g'(\hat{\mu}_b))^2 }
                              { \hat{\pi}_b },

    with the phasic-plus-tonic volatility

    .. math::

        \Omega_a^{(k)} = t^{(k)} \exp\!\left(
            \omega_a + \sum_{j} \kappa_{a,\check{a}_j} \hat{\mu}_{\check{a}_j}
        \right).

    The factor :math:`\lambda_a^2` scales the carried variance (scaling a Gaussian
    by :math:`\lambda_a` scales its variance by :math:`\lambda_a^2`); the drift is
    added after the autoregression, so the value-coupling term stays unscaled.

    .. note::

        Eq. 35 of [1]_ omits :math:`\lambda_a^2`; the two forms agree at
        :math:`\lambda_a = 1`.

    :math:`\bar{\pi}_a^{(k)}` is the *conditional* predicted precision
    (``conditional_expected_precision``): own variance plus volatility, without the
    parent-uncertainty bleed-through. It is the precision that enters the parent's
    Schur-complement posterior-step relaxation. :math:`\hat{\pi}_a^{(k)}` is the
    *marginal* predicted precision (``expected_precision``): the inverse of the
    marginal predictive variance, including the first-order Taylor value-coupling
    term. The bleed-through uses each parent's marginal predicted precision
    :math:`\hat{\pi}_b`, so that every parent passes its full marginal predictive
    variance on to its children. It uses *predicted*, not posterior, parent
    precisions, keeping the prediction schedule strictly top-down.

    The predicted volatility does not depend on the precision of the volatility
    parents. For a value :math:`x` of a volatility parent with coupling strength
    :math:`\kappa`, the predicted variance of the node is
    :math:`V(x) = \lambda_a^2 / \pi_a^{(k-1)} + t^{(k)} \exp(\omega_a + \kappa x)`,
    and the node moves towards evidence of variance :math:`\sigma` by the fraction
    :math:`V(x) / (V(x) + \sigma)`, which is concave in :math:`V` and lower than 1.
    The average of this fraction over the belief
    :math:`\mathcal{N}(\hat{\mu}, 1/\hat{\pi})` on the parent is therefore at most
    its value at the average variance :math:`\mathbb{E}[V(x)]` (Jensen's
    inequality). The average variance multiplies the volatility term of
    :math:`V(\hat{\mu})` by :math:`\exp(\kappa^2 / (2\hat{\pi}))`, which has no
    upper bound.

    The *effective precision* :math:`\gamma_a^{(k)}` is defined relative to the
    volatility-driven part of the marginal variance only,

    .. math::

        \gamma_a^{(k)} = \Omega_a^{(k)} \, \hat{\pi}_a^{(k)},

    and is consumed by the volatility-coupling posterior update at the volatility
    parent.

    With ``coupling_moments="exact"``, the coupling function of each value parent is
    replaced by its statistical linearisation under the predicted belief of the
    parent instead of its first-order Taylor expansion (see
    :func:`predict_value_coupling_variance`). The slope :math:`g'(\hat{\mu}_b)` becomes
    the mean slope :math:`A_b = \mathbb{E}[g'(x_b)]`, and the variance :math:`R_b` of
    the residual of the linear function is added to the conditional predicted
    variance:

    .. math::

        \frac{1}{\bar{\pi}_a^{(k)}} = \frac{\lambda_a^2}{\pi_a^{(k-1)}}
            + \Omega_a^{(k)} + \sum_{b} (t^{(k)} \alpha_{b,a})^2 R_b, \qquad
        \frac{1}{\hat{\pi}_a^{(k)}} = \frac{1}{\bar{\pi}_a^{(k)}}
            + \sum_{b} \frac{(t^{(k)} \alpha_{b,a} A_b)^2}{\hat{\pi}_b}.

    The marginal predicted variance is then the carried variance and the volatility
    plus :math:`\sum_b (t^{(k)} \alpha_{b,a})^2 \mathrm{Var}[g(x_b)]`.

    Leaves (input nodes) are not predicted by this function: see
    :func:`continuous_node_prediction` and :func:`predict_noise_precision`.

    Parameters
    ----------
    attributes :
        The attributes of the probabilistic network that contains the continuous state
        node.
    edges :
        The edges of the probabilistic network as a tuple of
        :py:class:`pyhgf.typing.AdjacencyLists`. For each node, the entry lists its
        value/volatility parents and children.
    node_idx :
        Index of the node that should be updated.
    coupling_moments :
        ``"taylor"`` (default) linearises the coupling functions at the expected
        means of the value parents. ``"exact"`` uses their moments under the
        predicted beliefs of the value parents.

    Returns
    -------
    expected_precision :
        The marginal predicted precision :math:`\hat{\pi}_a^{(k)}`.
    conditional_expected_precision :
        The conditional predicted precision :math:`\bar{\pi}_a^{(k)}`.
    effective_precision :
        The effective precision :math:`\gamma_a^{(k)}`; stored on the node for later
        use in the volatility-coupling posterior update.

    References
    ----------
    .. [1] Weber, L. A., Waade, P. T., Legrand, N., Møller, A. H., Stephan, K. E., &
       Mathys, C. (2026). The generalized hierarchical Gaussian filter.
       doi:10.7554/elife.110174.1
    """
    time_step = attributes[-1]["time_step"]

    # List the node's volatility parents
    volatility_parents_idxs = edges[node_idx].volatility_parents

    # Get the tonic volatility from the node
    total_volatility = attributes[node_idx]["tonic_volatility"]

    # Look at the (optional) volatility parents and add their value to the tonic
    # volatility to get the total volatility. The volatility parents enter at their
    # predicted means.
    if volatility_parents_idxs is not None:
        for volatility_parents_idx, volatility_coupling in zip(
            volatility_parents_idxs,
            attributes[node_idx]["volatility_coupling_parents"],
        ):
            total_volatility += (
                volatility_coupling
                * attributes[volatility_parents_idx]["expected_mean"]
            )

    # compute the predicted_volatility from the total volatility
    predicted_volatility = time_step * jnp.exp(total_volatility)
    predicted_volatility = jnp.where(
        predicted_volatility > 1e-128, predicted_volatility, jnp.nan
    )

    # Value-coupling term. The coupling function g of each value parent is replaced
    # by a linear function of the parent's value around μ̂_b; the variance each
    # parent adds through its slope A_b is (t · α · A_b)² / π̂_b, using the parent's
    # marginal predicted precision π̂_b (= `expected_precision`). The factor t arises
    # because the value-parent contribution to the mean is scaled by the time step in
    # :func:`predict_mean`. The slope is g'(μ̂_b) (first-order Taylor expansion) or,
    # with the exact moments, E[g'(x_b)], which leaves a residual variance.
    value_coupling_variance, residual_variance = predict_value_coupling_variance(
        attributes, edges, node_idx, coupling_moments
    )

    # Carried variance: scaling the belief by λ scales its variance by λ².
    carried_variance = (
        attributes[node_idx]["autoconnection_strength"] ** 2
    ) / attributes[node_idx]["precision"]

    # Conditional π̄_a: carried variance + volatility, no parent bleed-through
    # (the parent's Schur complement acts on this; the marginal would double-count).
    # With the exact moments, the residual of the linear function does not depend on
    # the parent's value and adds to the conditional variance.
    conditional_variance = carried_variance + predicted_volatility
    if coupling_moments == "exact":
        conditional_variance = conditional_variance + residual_variance
    conditional_expected_precision = 1 / jnp.maximum(
        conditional_variance, MIN_PREDICTED_VARIANCE
    )

    # Marginal π̂_a: conditional variance + value-coupling variance of the slopes.
    expected_precision = 1 / jnp.maximum(
        conditional_variance + value_coupling_variance,
        MIN_PREDICTED_VARIANCE,
    )

    # compute the effective precision (γ); only the volatility-driven part
    # enters γ, since γ is consumed by the volatility-coupling posterior update.
    effective_precision = predicted_volatility * expected_precision

    return expected_precision, conditional_expected_precision, effective_precision


@partial(jit, static_argnames=("edges", "node_idx", "coupling_moments"))
def continuous_node_prediction(
    attributes: dict,
    node_idx: int,
    edges: Edges,
    coupling_moments: str = "taylor",
    **args,
) -> dict:
    r"""Update the expected mean and expected precision of a continuous node [1]_.

    The precision prediction follows the relaxed HGF (rHGF) scheme, which marginalises
    over the value parents' variational Gaussians instead of treating them as point
    estimates. See :func:`predict_precision` for the precise formula and its additional
    variance term (the value-coupling Taylor term). Volatility parents enter at their
    predicted means.

    An input node is observed exactly. Without volatility parent, both of its
    predicted precisions are its ``precision``, the fixed precision of the
    observation noise. Its volatility parents are noise parents [1]_, which estimate
    this precision: both predicted precisions are then the noise precision of
    :func:`predict_noise_precision`, and its effective precision is 1.

    With ``coupling_moments="exact"``, the value parents enter the prediction through
    the moments of their coupling functions under their predicted beliefs (see
    :func:`predict_mean` and :func:`predict_precision`). The variance
    :math:`V^{\mathrm{res}}_u` of the residuals of the linearised coupling functions
    (:func:`predict_value_coupling_variance`) is added to the variance of the
    observation noise of an input node :math:`u`, so that both of its predicted
    precisions are :math:`1 / (1/\pi_u + V^{\mathrm{res}}_u)`, with :math:`\pi_u` its
    ``precision`` or its noise precision.

    .. note::
        The parameter structure also incorporates the value and volatility coupling
        strength with children and parents (i.e. `"value_coupling_parents"`,
        `"value_coupling_children"`, `"volatility_coupling_parents"`,
        `"volatility_coupling_children"`).

    Parameters
    ----------
    attributes :
        The attributes of the probabilistic nodes.
    node_idx :
        Pointer to the node that will be updated.
    edges :
        The edges of the probabilistic nodes as a tuple of
        :py:class:`pyhgf.typing.AdjacencyLists`. The tuple has the same length as the
        node number. For each node, the index lists the value and volatility parents
        and children.
    coupling_moments :
        ``"taylor"`` (default) linearises the coupling functions at the expected
        means of the value parents. ``"exact"`` uses their moments under the
        predicted beliefs of the value parents.

    Returns
    -------
    attributes :
        The updated attributes of the probabilistic nodes.

    See Also
    --------
    update_continuous_input_parents, update_binary_input_parents

    References
    ----------
    .. [1] Weber, L. A., Waade, P. T., Legrand, N., Møller, A. H., Stephan, K. E., &
       Mathys, C. (2026). The generalized hierarchical Gaussian filter.
       doi:10.7554/elife.110174.1
    """
    return _store_prediction(
        attributes,
        edges,
        node_idx,
        partial(predict_precision, coupling_moments=coupling_moments),
        coupling_moments,
    )


def is_noise_child(edges: Edges, node_idx: int) -> bool:
    """Return whether a node is an input node with a noise parent.

    A continuous leaf (a node of type 2 without value or volatility children) is an
    input node. Following [1]_, a volatility parent of an input node is a noise
    parent: it sets the variance of the observation noise rather than the volatility
    of a random walk. Its noise child is updated with the noise prediction error of
    :func:`pyhgf.updates.prediction_error.continuous.continuous_node_noise_prediction_error`.

    Parameters
    ----------
    edges :
        The edges of the probabilistic network.
    node_idx :
        Index of the node.

    Returns
    -------
    is_noise_child :
        ``True`` if the node is an input node with at least one volatility parent.

    References
    ----------
    .. [1] Weber, L. A., Waade, P. T., Legrand, N., Møller, A. H., Stephan, K. E., &
       Mathys, C. (2026). The generalized hierarchical Gaussian filter.
       doi:10.7554/elife.110174.1
    """
    edge = edges[node_idx]
    return (
        edge.node_type == 2
        and edge.value_children is None
        and edge.volatility_children is None
        and edge.volatility_parents is not None
    )


def predict_noise_precision(attributes: dict, edges: Edges, node_idx: int) -> Array:
    r"""Predict the precision of the observation noise of an input node.

    For an input node :math:`u` with noise parents :math:`q`, Eq. 66 of [1]_ gives

    .. math::

        \hat{\pi}_u^{(k)} = \frac{1}{\exp\left(\epsilon_u
            + \sum_q \kappa_{u,q} \hat{\mu}_q^{(k)}\right)},

    with the tonic observation noise :math:`\epsilon_u` given by the
    ``tonic_volatility`` of the input node, which is 0 for an input node. A tonic
    observation noise is equivalent to shifting the mean of a noise parent by
    :math:`\epsilon_u / \kappa_{u,q}`, since the updates of the noise parent depend
    on :math:`\epsilon_u + \kappa_{u,q} \mu_q` only. The ``precision`` of the input
    node is the precision of the observation noise of an input node without noise
    parent, and is not used here. The noise parents enter at their predicted means;
    [1]_ uses their previous posterior means, which are the same for a parent without
    drift and with an autoconnection strength of 1. The variance of the observation
    noise does not scale with the time step, and the noise parents enter as point
    estimates, as in [1]_, under both the relaxed and the mean-field predictions.

    Parameters
    ----------
    attributes :
        The attributes of the probabilistic network.
    edges :
        The edges of the probabilistic network.
    node_idx :
        Index of the input node.

    Returns
    -------
    noise_precision :
        The predicted precision :math:`\hat{\pi}_u^{(k)}` of the observation noise.

    References
    ----------
    .. [1] Weber, L. A., Waade, P. T., Legrand, N., Møller, A. H., Stephan, K. E., &
       Mathys, C. (2026). The generalized hierarchical Gaussian filter.
       doi:10.7554/elife.110174.1
    """
    log_noise_variance = attributes[node_idx]["tonic_volatility"]
    for noise_parent_idx, coupling in zip(
        edges[node_idx].volatility_parents,  # type: ignore
        attributes[node_idx]["volatility_coupling_parents"],
    ):
        log_noise_variance += coupling * attributes[noise_parent_idx]["expected_mean"]
    return jnp.exp(-log_noise_variance)


def _store_prediction(
    attributes: dict,
    edges: Edges,
    node_idx: int,
    precision_fn: Callable,
    coupling_moments: str = "taylor",
) -> dict:
    r"""Write the prediction of a continuous node to its attributes.

    An input node is observed exactly and does not drift between observations, so
    its predicted precisions do not come from ``precision_fn``. Without noise parent,
    both are its ``precision``, the precision of the observation noise. With noise
    parents, both are the noise precision of :func:`predict_noise_precision`, and
    the effective precision is :math:`\gamma_u = 1`, as for the noise child of [1]_
    (Eq. 73). Other nodes take the predicted precisions of ``precision_fn``.

    With ``coupling_moments="exact"``, :func:`predict_mean` takes this argument
    (``precision_fn`` is already bound to it), and the variance of the residuals of the linearised coupling
    functions (:func:`predict_value_coupling_variance`) is added to the variance of
    the observation noise of an input node, and to the known variance that the
    volatility updates of the parents of a state node read (``current_variance``).

    References
    ----------
    .. [1] Weber, L. A., Waade, P. T., Legrand, N., Møller, A. H., Stephan, K. E., &
       Mathys, C. (2026). The generalized hierarchical Gaussian filter.
       doi:10.7554/elife.110174.1
    """
    edge = edges[node_idx]
    is_input_node = edge.value_children is None and edge.volatility_children is None

    exact_moments = coupling_moments == "exact"
    if exact_moments:
        _, residual_variance = predict_value_coupling_variance(
            attributes, edges, node_idx, coupling_moments
        )

    if is_input_node and edge.volatility_parents is not None:
        noise_precision = predict_noise_precision(attributes, edges, node_idx)
        if exact_moments:
            noise_precision = 1.0 / (1.0 / noise_precision + residual_variance)
        expected_precision = conditional_expected_precision = noise_precision
        effective_precision = jnp.ones_like(noise_precision)
    elif is_input_node:
        expected_precision = attributes[node_idx]["precision"]
        if exact_moments:
            expected_precision = 1.0 / (1.0 / expected_precision + residual_variance)
        conditional_expected_precision = expected_precision
        effective_precision = jnp.zeros_like(expected_precision)
    else:
        expected_precision, conditional_expected_precision, effective_precision = (
            precision_fn(attributes, edges, node_idx)
        )

    # Carried variance, which the eHGF and unbounded volatility updates re-predict
    # from: the same quantity as in ``precision_fn``. With the exact moments, the
    # residual variance of the linearised coupling functions is known variance too.
    current_variance = (
        attributes[node_idx]["autoconnection_strength"] ** 2
    ) / attributes[node_idx]["precision"]
    if exact_moments and not is_input_node:
        current_variance = current_variance + residual_variance
    expected_mean = predict_mean(attributes, edges, node_idx, coupling_moments)
    attributes[node_idx]["temp"]["current_variance"] = current_variance
    attributes[node_idx]["expected_mean"] = expected_mean
    attributes[node_idx]["expected_precision"] = expected_precision
    attributes[node_idx]["temp"]["conditional_expected_precision"] = (
        conditional_expected_precision
    )
    attributes[node_idx]["temp"]["effective_precision"] = effective_precision

    return attributes


@partial(jit, static_argnames=("edges", "node_idx"))
def predict_precision_mean_field(
    attributes: dict, edges: Edges, node_idx: int
) -> tuple[Array, Array, Array]:
    r"""Compute the expected precision of a continuous state node (mean-field).

    The expected precision at time :math:`k` for a state node :math:`a` is given by
    [1]_:

    .. math::

        \hat{\pi}_a^{(k)} = \frac{1}
            {\frac{\lambda_a^2}{\pi_a^{(k-1)}} + \Omega_a^{(k)}}

    where :math:`\lambda_a` is the autoconnection strength and
    :math:`\Omega_a^{(k)}` is the *total predicted volatility*. This term is the
    sum of the tonic (endogenous) and phasic (exogenous) volatility, such as:

    .. math::

        \Omega_a^{(k)} = t^{(k)}
        \exp{ \left( \omega_a + \sum_{j=1}^{N_{vopa}} \kappa_j \hat{\mu}_a^{(k-1)} \right) }


    with :math:`\kappa_j` the volatility coupling strength with the volatility parent
    :math:`j`. The carried variance takes :math:`\lambda_a^2` because scaling the
    belief by :math:`\lambda_a` scales its variance by :math:`\lambda_a^2`.

    The *effective precision* :math:`\gamma_a^{(k)}` is given by:

    .. math::

        \gamma_a^{(k)} = \Omega_a^{(k)} \hat{\pi}_a^{(k)}

    This value is also saved in the node for later use during the update steps.


    Parameters
    ----------
    attributes :
        The attributes of the probabilistic network that contains the continuous state
        node.
    edges :
        The edges of the probabilistic network as a tuple of
        :py:class:`pyhgf.typing.Indexes`. The tuple has the same length as the number of
        nodes. For each node, the index list value/volatility - parents/children.
    node_idx :
        Index of the node that should be updated.

    Returns
    -------
    expected_precision :
        The new expected precision of the value parent.
    effective_precision :
        The effective_precision :math:`\gamma_a^{(k)}`. This value is stored in the
        node for later use in the update steps.

    References
    ----------
    .. [1] Weber, L. A., Waade, P. T., Legrand, N., Møller, A. H., Stephan, K. E., &
       Mathys, C. (2026). The generalized Hierarchical Gaussian Filter. eLife, 15,
       RP110174. https://doi.org/10.7554/eLife.110174.1

    """
    time_step = attributes[-1]["time_step"]

    volatility_parents_idxs = edges[node_idx].volatility_parents
    total_volatility = attributes[node_idx]["tonic_volatility"]

    if volatility_parents_idxs is not None:
        for volatility_parents_idx, volatility_coupling in zip(
            volatility_parents_idxs,
            attributes[node_idx]["volatility_coupling_parents"],
        ):
            total_volatility += (
                volatility_coupling
                * attributes[volatility_parents_idx]["expected_mean"]
            )

    predicted_volatility = time_step * jnp.exp(total_volatility)
    predicted_volatility = jnp.where(
        predicted_volatility > 1e-128, predicted_volatility, jnp.nan
    )

    # Carried variance: scaling the belief by λ scales its variance by λ².
    carried_variance = (
        attributes[node_idx]["autoconnection_strength"] ** 2
    ) / attributes[node_idx]["precision"]
    expected_precision = 1 / jnp.maximum(
        carried_variance + predicted_volatility,
        MIN_PREDICTED_VARIANCE,
    )
    effective_precision = predicted_volatility * expected_precision

    return expected_precision, expected_precision, effective_precision


@partial(jit, static_argnames=("edges", "node_idx"))
def continuous_node_prediction_mean_field(
    attributes: dict, node_idx: int, edges: Edges, **args
) -> dict:
    """Mean-field prediction step for a continuous node.

    Uses the canonical (g)HGF formula: no Taylor value-coupling variance term. Input
    nodes are predicted as in :func:`continuous_node_prediction`.

    Parameters
    ----------
    attributes :
        The attributes of the probabilistic nodes.
    node_idx :
        Pointer to the node that will be updated.
    edges :
        The edges of the probabilistic nodes as a tuple of
        :py:class:`pyhgf.typing.AdjacencyLists`. The tuple has the same length as the
        node number. For each node, the index lists the value and volatility parents
        and children.

    Returns
    -------
    attributes :
        The updated attributes of the probabilistic nodes.
    """
    return _store_prediction(attributes, edges, node_idx, predict_precision_mean_field)
